"""Bind the LaTeX text to computed numbers and compile both requested PDFs."""
from __future__ import annotations
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
import pandas as pd

ROOT=Path(__file__).resolve().parents[1]


def generated_values(root=ROOT):
    s=json.loads((root/"reports/phase1/audit_summary.json").read_text(encoding="utf-8"))
    q,d,b=s["quality"],s["diagnostics"],s["baseline"]
    values={"RawReviews":f'{q["raw_review_rows"]:,}',"DuplicateReviews":f'{q["exact_duplicate_excess"]:,}',
            "QuarantinedReviews":str(q["quarantined_rows"]),"AcceptedReviews":f'{sum(s["split"]["before_purge_rows"].values()):,}',
            "RetainedReviews":f'{sum(s["split"]["retained_rows"].values()):,}',"PurgedReviews":str(s["split"]["purged_rows"]),
            "TrainRows":f'{s["split"]["retained_rows"]["train"]:,}',"ValidationRows":f'{s["split"]["retained_rows"]["validation"]:,}',
            "TestRows":f'{s["split"]["retained_rows"]["test"]:,}',"TrainProducts":f'{s["split"]["retained_products"]["train"]:,}',
            "ValidationProducts":f'{s["split"]["retained_products"]["validation"]:,}',"TestProducts":f'{s["split"]["retained_products"]["test"]:,}',
            "NegRate":f'{b["negative_prevalence"]*100:.2f}',"MajorityAccuracy":f'{b["majority_training_accuracy"]*100:.2f}',
            "NegCount":f'{b["negative_count"]:,}',"MedianWords":f'{d["train_word_count_median"]:.0f}',
            "MaxWords":f'{d["train_word_count_max"]:,}',"ShortRows":f'{d["train_very_short_rows"]:,}',
            "LongRows":f'{d["train_very_long_rows"]:,}',"MissingBodyRows":str(d["train_missing_body_rows"]),
            "ShortRate":f'{d["train_very_short_rows"]/b["n"]*100:.2f}',"LongRate":f'{d["train_very_long_rows"]/b["n"]*100:.2f}',
            "TopTenShare":f'{d["top_10_products_train_share"]*100:.2f}',"DuplicateTextExcess":str(d["normalized_long_text_duplicate_excess"]),
            "RepeatedPairs":str(d["repeated_user_product_pairs"]),"BrierReference":f'{b["constant_probability_brier_training"]:.4f}',
            "LogLossReference":f'{b["constant_probability_log_loss_training"]:.4f}'}
    (root/"reports/generated_values.tex").write_text("% Generated by src.build_documents; do not edit.\n"+"\n".join('\\newcommand{\\'+k+'}{'+v+'}' for k,v in values.items())+"\n")


def compile_documents(root=ROOT):
    generated_values(root)
    if not shutil.which("xelatex"):
        raise RuntimeError("Install a TeX Live/MiKTeX distribution with XeLaTeX before building the PDFs.")
    env=os.environ.copy()
    env["TEXINPUTS"]=(root/"texmf").as_posix()+"//"+os.pathsep+env.get("TEXINPUTS","")
    directory=root/"reports"
    for stem in ["phase1","presentation"]:
        for attempt in range(2):
            result=subprocess.run(["xelatex","-interaction=nonstopmode","-halt-on-error",stem+".tex"],cwd=directory,env=env,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,text=True)
            if result.returncode:
                print(result.stdout[-6000:],file=sys.stderr)
                raise RuntimeError(f"XeLaTeX failed for {stem}; inspect reports/{stem}.log")
        print(f"Built reports/{stem}.pdf")


if __name__=="__main__":
    compile_documents()
